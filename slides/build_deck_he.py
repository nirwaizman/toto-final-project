def card(slide, l, t, w, h, color=CARD, line=CARD_LINE, radius=None):
    c = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, l, t, w, h)
    c.fill.solid(); c.fill.fore_color.rgb = color
    c.line.color.rgb = line; c.line.width = Pt(1.25); c.shadow.inherit = False
    if radius is not None:
        c.adjustments[0] = radius
    return c


def img_card(slide, path, l, t, w, h, caption=None):
    """Image inside a card; the image is fitted (aspect-preserved) into w x h and
    the card shrinks to hug it, so there is never dead space below the picture."""
    from PIL import Image
    iw, ih = Image.open(path).size
    pad = Inches(0.12)
    cap_h = Inches(0.4) if caption else 0
    avail_w, avail_h = w - 2 * pad, h - 2 * pad
    scale = min(avail_w / iw, avail_h / ih)
    pw, ph = int(iw * scale), int(ih * scale)
    card_w, card_h = pw + 2 * pad, ph + 2 * pad + cap_h
    cl = l + int((w - card_w) / 2)
    card(slide, cl, t, card_w, card_h, radius=0.04)
    slide.shapes.add_picture(path, cl + pad, t + pad, width=pw, height=ph)
    if caption:
        add_text(slide, cl, t + pad + ph, card_w, Inches(0.4), caption, size=11, color=MUTED, align=PP_ALIGN.CENTER)
    return card_h


def kpi(slide, l, t, w, h, value, label, color, size=34, label_size=13):
    c = card(slide, l, t, w, h, radius=0.08)
    c.line.color.rgb = color; c.line.width = Pt(2)
    add_text(slide, l, t + Inches(0.15), w, Inches(0.9), value, size=size, bold=True, color=color, align=PP_ALIGN.CENTER)
    add_text(slide, l, t + h - Inches(0.6), w, Inches(0.5), label, size=label_size, color=GRAY, align=PP_ALIGN.CENTER)


def arrow_left(slide, x_from, x_to, y, color=WHITE):
    conn = slide.shapes.add_connector(MSO_CONNECTOR.STRAIGHT, x_from, y, x_to, y)
    conn.line.color.rgb = color; conn.line.width = Pt(2.5)
    ln = conn.line._get_or_add_ln()
    tail = ln.makeelement(qn("a:tailEnd"), {"type": "triangle", "w": "lg", "len": "lg"})
    ln.append(tail)


