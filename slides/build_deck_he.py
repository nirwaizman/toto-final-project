def rtl(paragraph, align=PP_ALIGN.RIGHT):
    """Mark a paragraph as right-to-left and right-aligned."""
    pPr = paragraph._p.get_or_add_pPr()
    pPr.set("rtl", "1")
    paragraph.alignment = align


def add_bg(slide, color=DARK):
    bg = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, 0, 0, SW, SH)
    bg.fill.solid(); bg.fill.fore_color.rgb = color
    bg.line.fill.background(); bg.shadow.inherit = False
    slide.shapes._spTree.remove(bg._element)
    slide.shapes._spTree.insert(2, bg._element)


def add_text(slide, l, t, w, h, text, size=18, bold=False, color=WHITE, align=PP_ALIGN.RIGHT,
             font=FONT, spacing=1.15, anchor=None):
    box = slide.shapes.add_textbox(l, t, w, h)
    tf = box.text_frame; tf.word_wrap = True
    if anchor: tf.vertical_anchor = anchor
    for i, line in enumerate(text.split("\n")):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        r = p.add_run(); r.text = line
        r.font.size = Pt(size); r.font.bold = bold; r.font.color.rgb = color; r.font.name = font
        p.line_spacing = spacing
        rtl(p, align)
    return box


def add_bullets(slide, l, t, w, h, items, size=16, color=GRAY, bullet="◀", bullet_color=ORANGE, gap=10):
    """RTL bullet list. Each item may be 'bold part|rest' to emphasize a lead-in."""
    box = slide.shapes.add_textbox(l, t, w, h)
    tf = box.text_frame; tf.word_wrap = True
    for i, item in enumerate(items):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        rb = p.add_run(); rb.text = bullet + "  "
        rb.font.size = Pt(size - 4); rb.font.color.rgb = bullet_color; rb.font.name = FONT
        if "|" in item:
            lead, rest = item.split("|", 1)
            r1 = p.add_run(); r1.text = lead
            r1.font.size = Pt(size); r1.font.bold = True; r1.font.color.rgb = WHITE; r1.font.name = FONT
            r2 = p.add_run(); r2.text = rest
            r2.font.size = Pt(size); r2.font.color.rgb = color; r2.font.name = FONT
        else:
            r = p.add_run(); r.text = item
            r.font.size = Pt(size); r.font.color.rgb = color; r.font.name = FONT
        p.line_spacing = 1.25; p.space_after = Pt(gap)
        rtl(p)
    return box


